
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {JOBS,SPECIAL,ORIGINS} from '../src/reboot/data.js';
import {SAVE_KEY,SCHEMA,createLife,transition,jobEligibility,specialEligibility,actionStatus,remaining,currentEvent,currentJob,currentSpecial} from '../src/reboot/engine.js';
const rollHigh=()=>.99,rollLow=()=>0;
let assertions=0;
const verify=(value,message)=>{assert.ok(value,message);assertions++;};
const act=(s,a,rng=rollHigh)=>transition(s,a,rng);
const pass=(s,a,rng)=>{const out=act(s,a,rng);verify(out.result.ok,JSON.stringify({action:a,result:out.result}));return out.state};
const no=(s,a,rng)=>{const before=JSON.stringify(s),out=act(s,a,rng);verify(!out.result.ok,'Unexpected success: '+JSON.stringify(a));verify(JSON.stringify(s)===before,'Rejected action mutated original');return out;};
verify(JOBS.length===15,'15 genuine ordinary occupations');
verify(SPECIAL.length===5,'5 separately structured special careers');
verify(new Set(JOBS.map(j=>j.id)).size===JOBS.length,'Unique occupation IDs');
verify(new Set(SPECIAL.map(j=>j.id)).size===SPECIAL.length,'Unique special career IDs');
verify(SPECIAL.every(c=>c.actions.length>=2),'Every special career has two unique actions');
verify(!JOBS.some(j=>SPECIAL.some(c=>c.id===j.id)),'Special careers are never ordinary jobs');
verify(SAVE_KEY==='one-piece-life:reboot:v1','Dedicated fresh save key');
let s=createLife({name:'Luffy <script>',origin:'East Blue'},rollHigh);
verify(s.schema===SCHEMA&&s.age===0&&s.alive,'Fresh life from birth');
verify(s.player.name.includes('<script>'),'Engine never destroys player text; UI escapes it');
verify(s.history.length===1&&s.career.job===null&&s.career.special===null,'New life starts cleanly');
verify(ORIGINS.includes(s.player.origin),'Valid origin');
verify(jobEligibility(s,JOBS[0]).includes('16'),'No baby job applications');
no(s,{type:'apply',id:'dock'});
no(s,{type:'special-join',id:'marine'});
no(s,{type:'activity',id:'study'});
for(let age=1;age<=16;age++){const prev=s;s=pass(s,{type:'age'});verify(s.age===age&&s!==prev,'Age changes one year with immutable input');}
verify(!s.pending,'High roll produces no interruption');
verify(s.player.intellect>45,'School increases intelligence from 6 to 16');
verify(s.career.job===null,'No automatically assigned profession');
verify(actionStatus(s,'work').includes('emploi'),'Working requires a job');
no(s,{type:'activity',id:'work'});
s=pass(s,{type:'apply',id:'waiter'},rollLow);
verify(currentJob(s).id==='waiter'&&s.career.special===null,'Ordinary hire does not create special path');
no(s,{type:'special-join',id:'marine'});
const original=JSON.stringify(s),beforeWorkMoney=s.player.money;
s=pass(s,{type:'activity',id:'work'});
verify(s.career.job.xp===14,'Work produces career XP');
verify(s.player.money>beforeWorkMoney,'Work action generates an actual bonus');
verify(original!==JSON.stringify(s),'Work changes state');
s=pass(s,{type:'activity',id:'work'});
no(s,{type:'activity',id:'work'});
verify(remaining(s,'work')===0,'Yearly quota enforced');
s=pass(s,{type:'age'});
verify(s.age===17&&remaining(s,'work')===2,'Aging resets annual action limits');
verify(s.history.some(h=>h.title==='Salaire annuel'),'Ordinary annual salary is recorded');
s=pass(s,{type:'quit-job'});
verify(s.career.job===null,'Resigning removes ordinary career');
s=pass(s,{type:'special-join',id:'marine'});
verify(currentSpecial(s).id==='marine'&&s.career.job===null,'Marine is independent from ordinary jobs');
no(s,{type:'apply',id:'cook'});
const level=s.career.special.rank;
s=pass(s,{type:'special-action',id:'patrol'},rollLow);
verify(s.career.special.rank>=level,'Special activity awards progress');
s=pass(s,{type:'special-action',id:'train'},rollLow);
no(s,{type:'special-action',id:'train'});
s=pass(s,{type:'special-leave'});
verify(s.career.special===null,'Special exit is independent');
s=pass(s,{type:'age'});
verify(s.age===18,'Next age is 18');
s=pass(s,{type:'special-join',id:'pirate',method:'create'});
verify(s.career.special.crew===1&&s.career.special.method==='create','Pirate founding uses separate creation route');
s=pass(s,{type:'special-action',id:'recruit'},rollLow);
verify(s.career.special.crew===2,'Real crew recruitment increments crew');
s=pass(s,{type:'special-leave'});
s=pass(s,{type:'special-join',id:'pirate',method:'join'});
verify(s.career.special.crew===4&&s.career.special.method==='join','Pirate joining route is distinct');
verify(s.history.length>8,'Annual diary records choices');
verify(s.history[0].age<=s.age,'Diary has sensible year ordering');
verify(s.history.length<=100,'Diary has a maximum size');
const fresh=createLife({name:'Test',origin:'Grand Line'},rollHigh);
let school=fresh;
for(let i=0;i<5;i++)school=pass(school,{type:'age'},rollHigh);
verify(school.age===5,'Five-year threshold works');
school=pass(school,{type:'age'},rollLow);
verify(!!school.pending&&!!currentEvent(school),'Life event triggers genuine choice');
const blocked=act(school,{type:'age'});
verify(!blocked.result.ok,'Cannot bypass pending decision');
const ev=currentEvent(school);
const chosen=ev.choices[0].id;
school=pass(school,{type:'choose',id:chosen});
verify(school.pending===null,'Choice resolves interruption');
verify(school.history[0].description===ev.choices[0].text,'Consequences appear in journal');
school=pass(school,{type:'age'},rollHigh);
verify(school.age===7,'Annual loop resumes after resolving choice');
let bonds=school;
bonds=pass(bonds,{type:'meet'},rollLow);
verify(bonds.relations.length===2,'New person created via action');
const relation=bonds.relations[1],oldBond=relation.bond;
bonds=pass(bonds,{type:'interact',id:relation.id,method:'talk'});
verify(bonds.relations[1].bond>oldBond,'Direct person interaction improves bond');
no(bonds,{type:'interact',id:'nonexistent',method:'talk'});
verify(JSON.parse(JSON.stringify(bonds)).relations.length===2,'State is serializable');
const gov={...s,player:{...s.player,intellect:10},career:{job:null,special:null}};
verify(specialEligibility(gov,SPECIAL.find(c=>c.id==='government')).includes('Intelligence'),'Government gate is unique');
const html=readFileSync('index.html','utf8');
verify(html.includes('src/reboot/ui.js')&&!html.includes('src/v95/'),'Root loads only the reboot experience');
verify(html.includes('lang="fr"'),'French first');
verify(existsSync('classic.html'),'Historical playable version preserved');
const legacy=readFileSync('classic.html','utf8');
verify(legacy.includes('v95')&&legacy.length>100000,'Legacy app archived intact');
const ui=readFileSync('src/reboot/ui.js','utf8');
verify(ui.includes('escapeHtml')&&ui.includes('escapeHtml(p.name)'),'User input is escaped for HTML');
verify(ui.includes('data-career="jobs"')&&ui.includes('data-career="special"'),'Visible separation between career kinds');
verify(ui.includes('data-do="new-life"')&&ui.includes('window.confirm'),'Fresh reset demands confirmation');
verify(ui.includes('role="status"'),'Clear action feedback');
const sw=readFileSync('sw.js','utf8');
verify(sw.includes('one-piece-life-reboot-v13-1')&&!sw.includes('src/v95'),'PWA caches only reboot dependencies');
console.log('V13 reboot: '+assertions+' checks passed. Independent immutable engine, career separation, annual loop, relationships, choices, legacy preservation.');
