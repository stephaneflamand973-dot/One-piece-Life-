import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx={console,Math,JSON,Object,Array,String,Number,Map,Set};ctx.window=ctx;vm.createContext(ctx);
for(const path of ['src/core/module-registry.js','src/data/economy-v105.js','src/v105/economy-engine-v105.js'])
 vm.runInContext(fs.readFileSync(path,'utf8'),ctx,{filename:path});
const m=ctx.OPL_MODULES.get('economyEngineV105'),d=ctx.OPL_MODULES.get('economyDataV105');
assert(m?.version==='10.5.0'&&d?.version==='10.5.0','Economic modules absent');
assert(Object.keys(d.assets).length===6,'Missing six economic asset types');
assert(Object.values(d.assets).filter(x=>x.category==='business').length===3,'Active businesses missing');
const c={age:25,year:25,energy:100,money:150000,priceIndex:1,prosperity:65,skill:45,alive:true,pending:false,travel:false,roll:0,efficiency:1};
let s=m.normalize({},25),copy=JSON.stringify(s);
assert(s.bought===0&&s.operated===0&&s.holdings.dojo===0,'Invalid initial economic ledger');
assert(!m.purchaseStatus(s,'dojo',{...c,age:15}).available,'Minor can buy major investments');
assert(!m.purchaseStatus(s,'dojo',{...c,money:15}).available,'Unaffordable purchase allowed');
assert(!m.purchaseStatus(s,'dojo',{...c,travel:true}).available,'Travel should block buying');
assert(!m.purchaseStatus(s,'dojo',{...c,pending:true}).available,'Pending decision should block buying');
const dojo=m.buy(s,'dojo',c);
assert(dojo.ok&&dojo.cost===16000&&dojo.energy===2&&dojo.state.holdings.dojo===1,'Training investment did not purchase');
assert(JSON.stringify(s)===copy,'Purchase mutated the original state');
s=dojo.state;
assert(m.perks(s).training===1.09,'Dojo has no useful training benefit');
assert(m.purchasePrice(s,'dojo',1)>dojo.cost,'Asset upgrade should cost more');
const clinic=m.buy(s,'clinic',c);
assert(clinic.ok&&clinic.state.bought===2&&m.perks(clinic.state).recovery===1.18,'Recovery equipment perk missing');
s=clinic.state;
assert(!m.purchaseStatus(s,'shop',c).available&&m.buy(s,'shop',c).ok===false,'Two purchases per year not enforced');
assert(m.purchaseStatus(s,'shop',{...c,year:26}).available,'Next year purchase quota did not reset');
const renewed=m.normalize(s,26);
assert(renewed.bought===0&&renewed.operated===0&&renewed.holdings.dojo===1&&renewed.invested>0,'Aging must renew actions without erasing assets');
const shop=m.buy(renewed,'shop',{...c,year:26});
assert(shop.ok&&shop.state.holdings.shop===1,'Shop purchase failed');
assert(m.operatingStatus(shop.state,'shop',{...c,year:26}).available,'Operating purchased enterprise blocked');
assert(!m.operatingStatus(shop.state,'shipyard',{...c,year:26}).available,'Operating non-owned enterprise allowed');
assert(!m.operatingStatus(shop.state,'shop',{...c,year:26,money:0}).available,'Enterprise operating costs ignored');
let state=shop.state;
const originalMoney=20000;
const profitable=m.operate(state,'shop',{...c,year:26,money:originalMoney,roll:0});
assert(profitable.ok&&profitable.success&&profitable.revenue>profitable.fee&&profitable.net>0,'Profitable business did not pay');
state=profitable.state;
const unprofitable=m.operate(state,'shop',{...c,year:26,money:originalMoney,roll:.99});
assert(unprofitable.ok&&!unprofitable.success&&unprofitable.net===-unprofitable.fee,'Failed enterprise should lose its operating cost');
state=unprofitable.state;
const third=m.operate(state,'shop',{...c,year:26,money:originalMoney,roll:0,efficiency:.65});
assert(third.ok&&third.state.operated===3,'Three operating decisions not tracked');
assert(!m.operatingStatus(third.state,'shop',{...c,year:26}).available,'Business operation annual cap bypassed');
assert(m.normalize(third.state,27).operated===0&&m.normalize(third.state,27).netOperating===third.state.netOperating,'Annual reset must preserve actual business result');
const finances=m.wealth(third.state,40000,{year:26,priceIndex:1});
assert(finances.netWorth>40000&&finances.assetValue>0,'Purchased assets not counted toward net worth');
assert(m.perks({holdings:{navigation:2,shipyard:2,shop:2,dojo:2,clinic:2},year:25}).navigationCost===4,'Navigation office does not save energy');
assert(m.perks({holdings:{navigation:2,shipyard:2,shop:2,dojo:2,clinic:2},year:25}).tradeExpertise>.03,'Commerce advantage missing');
const restored=m.normalize(JSON.parse(JSON.stringify(third.state)),26);
assert(restored.holdings.shop===1&&restored.history.length===6,'Economic ledger does not survive save/load');
const corrupted=m.normalize({year:29,holdings:{dojo:99,shop:-999,evil:17},bought:999,operated:999,invested:-9,history:Array(100).fill({type:'hacked',id:'evil',amount:Infinity})},29);
assert(corrupted.holdings.dojo===2&&corrupted.holdings.shop===0&&corrupted.holdings.evil===undefined,'Malformed assets accepted');
assert(corrupted.bought===2&&corrupted.operated===3&&corrupted.invested===0&&corrupted.history.length===30,'Unsafe finance data escaped clamps');
const html=fs.readFileSync('index.html','utf8'),sw=fs.readFileSync('sw.js','utf8'),manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
assert(html.includes("const GAME_VERSION = '12.0.0'")&&html.includes('src/v105/economy-engine-v105.js'),'V10.5 release missing');
assert(html.includes('function v105RenderEconomy()')&&html.includes('function v105SelectTarget(kind,id)'),'Economy selection UI missing');
assert(html.includes('trainProgress(Math.max(.35,2*factor*v105Perks().training))'),'Training equipment not applied');
assert(html.includes('v105Perks().recovery'),'Recovery equipment not applied');
assert(html.includes('costOverrides:{work:cm&&cs?cm.workCost(cs):12,navigation:v105Perks().navigationCost}'),'Navigation energy perk not applied');
assert(html.includes('function v100AdvanceYear()'),'Manual aging must survive');
assert(sw.includes('one-piece-life-v12-0-0')&&sw.includes('src/v105/economy-engine-v105.js'),'PWA assets missing');
assert(manifest.description.includes('V12.0.0'),'Installable app is stale');
new Function(html.match(/<script>([\s\S]*?)<\/script>/)?.[1]||'');
console.log('V10.5 ECONOMY QA OK',JSON.stringify({assets:Object.keys(d.assets).length,purchaseLimit:d.buyLimit,operateLimit:d.operateLimit,netFirst:profitable.net,netFailure:unprofitable.net}));
