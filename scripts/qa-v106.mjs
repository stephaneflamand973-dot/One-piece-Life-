import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const c={console,Math,JSON,Object,Array,String,Number,Map,Set};c.window=c;vm.createContext(c);
for(const file of ['src/core/module-registry.js','src/data/action-v102.js','src/v102/action-engine-v102.js','src/data/adventure-v106.js','src/v106/adventure-engine-v106.js'])
 vm.runInContext(fs.readFileSync(file,'utf8'),c,{filename:file});
const engine=c.OPL_MODULES.get('adventureEngineV106'),data=c.OPL_MODULES.get('adventureDataV106');
const actions=c.OPL_MODULES.get('actionDataV102'),registry=c.OPL_MODULES.get('actionEngineV102');
assert.equal(engine.version,'10.6.0');assert.equal(data.version,'10.6.0');
assert.equal(Object.keys(actions.actions).length,15);assert.equal(Object.keys(data.actions).length,4);
const ctx={year:23,age:23,island:'Shells Town',alive:true,pending:false,travel:false,money:2000,energy:100,
  navigation:35,stealth:30,command:50,crewSupport:50,danger:28,missionId:'qa_mission',crewActive:true,efficiency:1};
let s=engine.normalize({},23,ctx.island);
assert.equal(s.preparedness,0);assert.equal(s.missionBonus,0);
assert(!engine.status(s,'expedition_prepare',{...ctx,age:11}).available,'Age gate omitted');
assert(!engine.status(s,'expedition_prepare',{...ctx,pending:true}).available,'Pending decision ignored');
assert(!engine.status(s,'expedition_prepare',{...ctx,travel:true}).available,'Travel lock bypassed');
assert(!engine.status(s,'expedition_prepare',{...ctx,money:399}).available,'Missing Berry affordability gate');
assert(!engine.status(s,'expedition_command',{...ctx,crewActive:false}).available,'Command without crew');
assert(!engine.status(s,'expedition_coordinate',{...ctx,missionId:''}).available,'Mission planning without accepted mission');
const odds=engine.scoutPreview(s,ctx);
assert(odds.chance>=.22&&odds.chance<=.94,'Odds out of range');
assert(engine.scoutPreview(s,{...ctx,danger:90}).chance<odds.chance,'Danger ignored in odds');
assert(engine.scoutPreview(engine.selectApproach(s,'cautious',23,ctx.island),ctx).chance>engine.scoutPreview(engine.selectApproach(s,'daring',23,ctx.island),ctx).chance,'Approach not reflected in odds');
const start=engine.perform(s,'expedition_prepare',ctx);
assert(engine.scoutPreview(start.state,ctx).chance>odds.chance,'Preparation not reflected in odds');
assert(start.ok&&start.cost===400&&start.energy===5&&start.state.preparedness>0,'Plan must cost money and yield preparedness');
assert.equal(s.preparedness,0,'Engine must be pure and not mutate source state');
s=start.state;
const command=engine.perform(s,'expedition_command',ctx);assert(command.ok&&command.state.commandBoost>0);s=command.state;
const coordinate=engine.perform(s,'expedition_coordinate',ctx);assert(coordinate.ok&&coordinate.state.missionBonus>0);s=coordinate.state;
assert(engine.missionBonus(s,'qa_mission',23,ctx.island)>s.missionBonus,'Command synergy missing');
assert(engine.missionBonus(s,'other_mission',23,ctx.island)<engine.missionBonus(s,'qa_mission',23,ctx.island),'Mission plan leaks to unrelated assignment');
const cleared=engine.consumeMission(s,'qa_mission',23,ctx.island);
assert.equal(cleared.missionBonus,0);assert.equal(cleared.missionId,'');
const win=engine.perform(s,'expedition_scout',{...ctx,roll:0,injuryRoll:1});
assert(win.ok&&win.success&&win.state.expeditions===1&&win.state.discoveries===1,'Successful scout missing');
const fail=engine.perform(win.state,'expedition_scout',{...ctx,roll:1,injuryRoll:0});
assert(fail.ok&&!fail.success&&fail.state.expeditions===2&&fail.state.discoveries===1,'Failed scout gave guaranteed discovery');
assert(fail.healthLoss>=1,'Failed dangerous expedition can hurt player');
assert(!engine.status(s,'expedition_prepare',{...ctx,energy:0}).available,'Energy gate omitted');
assert(engine.normalize(s,24,'Water 7').preparedness===0,'Preparations persist after changing islands');
assert(engine.normalize(s,24,ctx.island).missionBonus===s.missionBonus,'Aging improperly grants or clears mission plan');
assert(engine.normalize(s,24,ctx.island).commandBoost===0,'Crew command bonus should expire at the next annual action reset');
const bad=engine.normalize({year:23,preparedness:Infinity,commandBoost:999,missionBonus:-5,totalCosts:-1,expeditions:1e16,history:Array(40).fill({kind:'hack',place:'x'})},23,'Water 7');
assert(bad.preparedness>=0&&bad.preparedness<=80&&bad.commandBoost===12&&bad.missionBonus===0&&bad.history.length===24);
let ledger=registry.normalize({},23);
for(let i=0;i<3;i++){
 const before=registry.status(ledger,'expedition_scout',23,{alive:true,pending:false,land:true,energy:100});
 assert(before.available,'Scout quota prematurely spent');
 const out=registry.perform(ledger,'expedition_scout',23,{alive:true,pending:false,land:true,energy:100},()=>({detail:'Reconnaissance'}));
 assert(out.changed);ledger=out.state;
}
assert(!registry.status(ledger,'expedition_scout',23,{alive:true,pending:false,land:true,energy:100}).available,'Scout quota bypass');
const renewed=registry.nextYear(ledger,24);assert(renewed.spent.expedition_scout===0&&renewed.total===ledger.total,'New year must only replenish quota');
const html=fs.readFileSync('index.html','utf8'),sw=fs.readFileSync('sw.js','utf8');
const manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
assert(html.includes("const GAME_VERSION = '10.8.0'")&&html.includes('src/v106/adventure-engine-v106.js'),'Game V10.6 modules missing');
assert(html.includes('function v106RenderAdventure()')&&html.includes('v106FinishMission(m)')&&html.includes('odds.injuryChance'),'V10.6 visible probabilities missing');
assert(html.includes('function v100AdvanceYear()')&&!html.includes("p.money+=result.pay;advanceClock(12)"),'Manual aging regressed');
assert(sw.includes('one-piece-life-v10-8-0')&&sw.includes('src/v106/adventure-v106.css'),'Offline V10.6 bundle missing');
assert(manifest.description.includes('V10.8'),'PWA manifest outdated');
new Function(html.match(/<script>([\s\S]*?)<\/script>/)?.[1]||'');
console.log('V10.6 EXPEDITION QA OK',JSON.stringify({actions:Object.keys(data.actions).length,prepared:start.state.preparedness,command:command.state.commandBoost,mission:coordinate.state.missionBonus,remaining:renewed.spent.expedition_scout}));
