import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const paths=['src/core/module-registry.js','src/data/career-v103.js','src/v103/career-engine-v103.js'];
const context={console,Math,JSON,Object,Array,String,Number,Set,Map};context.window=context;vm.createContext(context);
for(const path of paths)vm.runInContext(fs.readFileSync(path,'utf8'),context,{filename:path});
const engine=context.OPL_MODULES.get('careerEngineV103'),data=context.OPL_MODULES.get('careerDataV103');
assert(engine?.version==='10.3.0'&&data?.version==='10.3.0','Career modules missing');
assert(Object.keys(data.profiles).length===6,'Every playable faction must have its own pay profile');
assert(Object.keys(data.modes).length===3,'Work intensity choices missing');
assert(Object.keys(data.actions).length===3,'Professional interactions missing');
const identity='Marine|Marine',ctx={identity,faction:'Marine',career:'Marine',year:21,rankIndex:1,trust:55,standing:50,energy:100,careerActive:true,travel:false,alive:true,pending:false,roll:.5};
let state=engine.normalize({},identity);
assert(state.performance===30&&state.workSessions===0&&state.mode==='steady','Initial career state incorrect');
const oldState=JSON.stringify(state);
const regular=engine.workSession(state,{...ctx,efficiency:1});
assert(JSON.stringify(state)===oldState,'Pure work engine mutated caller state');
assert(regular.pay>0&&regular.xp>0&&regular.cost===12&&regular.state.performance>30,'A work action must have real, measurable effects');
state=engine.selectMode(state,'intensive');
assert(engine.workCost(state)===18,'Intensive work does not cost 18 energy');
const intense=engine.workSession(state,{...ctx,efficiency:1});
const baseline=engine.workSession(engine.selectMode(state,'steady'),{...ctx,efficiency:1});
assert(intense.pay>baseline.pay&&intense.xp>baseline.xp,'Intensive work is not more rewarding');
const strategic=engine.workSession(engine.selectMode(state,'strategic'),{...ctx,efficiency:1});
assert(strategic.pay<baseline.pay&&strategic.delta.influence>0&&strategic.delta.trust>baseline.delta.trust,'Strategic work trade-offs missing');
const cheap=engine.workSession(engine.selectMode(state,'steady'),{...ctx,efficiency:.42});
assert(cheap.pay<baseline.pay&&cheap.xp<=baseline.xp,'Diminishing work returns ignored');
assert(engine.profile('Pirates').basePay!==engine.profile('Marine').basePay,'Faction salaries are identical');
assert(engine.profile('Civil').label==='Métiers civils','Civil career fallback broken');
assert(!engine.status(state,'career_bonus',ctx).available,'Prime should be locked before any work');
assert(!engine.status(state,'career_initiative',{...ctx,travel:true}).available,'Career interactions should be disabled at sea');
assert(!engine.status(state,'career_support',{...ctx,energy:0}).available,'Career action energy validation missing');
assert(!engine.status(state,'career_support',{...ctx,pending:true}).available,'Career action ignored pending decision');
assert(!engine.status(state,'career_support',{...ctx,careerActive:false}).available,'Career action without a career permitted');
const support=engine.initiative(state,'career_support',{...ctx,efficiency:1});
assert(support.ok&&support.xp===2&&support.state.performance===35&&support.delta.trust>0,'Team support effects invalid');
const initiative=engine.initiative(state,'career_initiative',{...ctx,efficiency:.8});
assert(initiative.ok&&initiative.xp===4&&initiative.performanceGain===7&&initiative.delta.influence>0,'Initiatives did not respect diminishing efficiency');
let worker=regular.state;
worker=engine.workSession(worker,{...ctx,efficiency:.78}).state;
worker=engine.workSession(worker,{...ctx,efficiency:.58}).state;
worker=engine.workSession(worker,{...ctx,efficiency:.42}).state;
assert(worker.performance>=55,'Working across the year cannot unlock bonus eligibility');
assert(!engine.status(worker,'career_bonus',{...ctx,standing:20}).available,'Bonus needs standing');
assert(engine.status(worker,'career_bonus',ctx).available,'Eligible bonus remains blocked');
const reward=engine.bonus(worker,{...ctx,roll:0});
assert(reward.ok&&reward.approved&&reward.pay>0&&reward.state.bonusEarned===reward.pay,'Approved bonus not paid');
const rejected=engine.bonus(worker,{...ctx,roll:.9999});
assert(rejected.ok&&!rejected.approved&&rejected.pay===0,'Rejection outcome not handled');
assert(JSON.stringify(worker)===JSON.stringify(regular.state)?false:true,'Work state unexpectedly unchanged');
const rerolled=engine.normalize(reward.state,identity);
assert(rerolled.workSessions===4&&rerolled.bonusEarned===reward.pay,'Save serialization loses career ledger');
const switched=engine.normalize(reward.state,'Pirates|Pirate');
assert(switched.performance===30&&switched.workSessions===0&&switched.bonusEarned===0,'Career-switch exploit: old performance carried across factions');
const malformed=engine.normalize({identity,performance:9000,workSessions:-3,earned:-99,mode:'fake',history:Array(300).fill({kind:'invalid'.repeat(20),money:9999999999,year:999999})},identity);
assert(malformed.performance===100&&malformed.workSessions===0&&malformed.earned===0&&malformed.mode==='steady'&&malformed.history.length===12,'Invalid save data not bounded');
const index=fs.readFileSync('index.html','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert(index.includes("const GAME_VERSION = '10.9.0'")&&index.includes('src/v103/career-engine-v103.js'),'Game has not loaded V10.3');
assert(sw.includes('one-piece-life-v10-9-0')&&sw.includes('src/v103/career-engine-v103.js'),'Offline cache is stale');
assert(index.includes('function v103RenderCareer()')&&index.includes('function v103SetMode(id)'),'Active career UI missing');
assert(index.includes('function v100AdvanceYear()'),'Aging system must remain manual');
new Function(index.match(/<script>([\s\S]*?)<\/script>/)?.[1]||'');
console.log('V10.3 CAREERS QA OK',JSON.stringify({factions:Object.keys(data.profiles).length,modes:Object.keys(data.modes),actions:Object.keys(data.actions),examplePay:regular.pay}));
